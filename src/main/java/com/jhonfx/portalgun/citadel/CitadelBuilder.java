    private static void openCouncil(ServerLevel level,BlockPos center,BlockState frame,BlockState glass,BlockState light){
        // Domed outer shell
        publicPlaza(level,center,11,Blocks.SMOOTH_QUARTZ.defaultBlockState(),frame,light);
        for(int y=1;y<=16;y++)for(int i=0;i<360;i+=12){
            double a=Math.toRadians(i);int r=11-y/4;
            if(r<5)r=5;BlockPos p=center.offset((int)Math.round(Math.cos(a)*r),y,(int)Math.round(Math.sin(a)*r));
            set(level,p,(i%48==0)?frame:glass);
        }
        ring(level,center.above(17),6,light);

        // ── Central holoscreen pillar (displays Council business) ────────────
        for (int y = 1; y <= 6; y++) set(level, center.above(y), ModBlocks.OMEGA_ENERGY_GLASS.get().defaultBlockState());
        set(level, center.above(7), light);

        // ── Round table (raised ring platform around the pillar) ──────────────
        for (int x = -4; x <= 4; x++) for (int z = -4; z <= 4; z++) {
            double d = Math.sqrt(x*x + z*z);
            if (d >= 2.2 && d <= 4.0) {
                set(level, center.offset(x, 1, z), Blocks.SMOOTH_QUARTZ.defaultBlockState());
                if ((x + z & 3) == 0) set(level, center.offset(x, 1, z), light);
            }
        }

        // ── 5 Council seats around the table, evenly spaced ────────────────────
        for (int i = 0; i < 5; i++) {
            double a = i * Math.PI * 2 / 5.0;
            int sx = (int) Math.round(Math.cos(a) * 6.0);
            int sz = (int) Math.round(Math.sin(a) * 6.0);
            BlockPos seatPos = center.offset(sx, 1, sz);
            // Seat platform + backrest
            set(level, seatPos, frame);
            set(level, seatPos.above(), Blocks.PURPLE_STAINED_GLASS.defaultBlockState());
            // Podium light
            set(level, seatPos.relative(net.minecraft.core.Direction.UP, 2), light);
        }

        // ── Entrance path marker ─────────────────────────────────────────────
        for (int z = 9; z <= 11; z++) set(level, center.offset(0, 1, z), frame);
    }

