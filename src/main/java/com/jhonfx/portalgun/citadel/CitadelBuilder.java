        java.util.List<CitadelNpcEntity> all=level.getEntitiesOfClass(CitadelNpcEntity.class,new AABB(CENTER).inflate(92));
        String[] names={"Rick D-151","Rick B-921","Rick J-440","Rick K-083","Rick V-706","Rick A-113","Rick G-217","Rick H-604","Morty D-151","Morty B-921","Morty J-440","Morty K-083"};
