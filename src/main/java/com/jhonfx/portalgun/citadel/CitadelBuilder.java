    public static void ensureBuilt(ServerLevel level) {
        if (com.jhonfx.portalgun.curve.CurveSavedData.get(level).broken()) {
            if (com.jhonfx.portalgun.curve.CurveSavedData.get(level).collapseTicks() == 0) ensureRefuge(level);
            return; // A return trip must never repair the destroyed Curve or repopulate the city.
        }
        CitadelSavedData data = CitadelSavedData.get(level);
        if (data.getLayoutVersion() < CURRENT_LAYOUT_VERSION) {
            CitadelV4Layout.request(level);
            return;
        }
        if (!data.isBuilt()) {
            build(level);
            data.markBuilt();
        }
        ensureExpansion(level);
        decorateCurveWing(level);
        ensurePersonnel(level);
        ensureDistrictPopulation(level);
        // Garantia: CURVE_CORE e DIMENSIONAL_DRIVE sempre presentes na Curva Finita Central.
        // O rebuildCombatCitadel pode sobrescrever esses blocos com publicPlaza — restauramos aqui.
        ensureCurveWingMachinery(level);
        ensureNavigation(level);
    }

    static void finishV4(ServerLevel level) {
        CitadelSavedData data=CitadelSavedData.get(level);
        data.markBuilt();
        data.setLayoutVersion(CURRENT_LAYOUT_VERSION);
        ensureExpansion(level);
        ensureCurveWingMachinery(level);
        decorateCurveWing(level);
        ensurePersonnel(level);
        ensureNavigation(level);
        buildV7Interiors(level);
    }

    /** Opens real walkable corridors through dome rims, tower bulkheads and transit tubes. */
    private static void ensureNavigation(ServerLevel level){
        CitadelSavedData data=CitadelSavedData.get(level);if(data.getNavigationVersion()>=6)return;
        BlockPos hub=new BlockPos(0,96,0);
        carveRoute(level,hub,new BlockPos(-82,96,12),3);
        carveRoute(level,hub,new BlockPos(86,96,8),3);
        carveRoute(level,hub,new BlockPos(-18,96,-82),3);
        carveRoute(level,hub,new BlockPos(0,96,-76),3);
        // Wide, unobstructed concourses around every satellite terminal. This
        // also repairs worlds where an older tower shell covered the bridge exit.
        for(BlockPos district:new BlockPos[]{new BlockPos(-82,96,12),new BlockPos(86,96,8),new BlockPos(-18,96,-82)}){
            for(int x=-8;x<=8;x++)for(int z=-8;z<=8;z++)if(x*x+z*z<=64){
                level.setBlock(district.offset(x,0,z),(Math.abs(x)+Math.abs(z))%7==0?Blocks.SEA_LANTERN.defaultBlockState():ModBlocks.CITADEL_ALLOY.get().defaultBlockState(),2);
                for(int y=1;y<=5;y++)level.setBlock(district.offset(x,y,z),Blocks.AIR.defaultBlockState(),2);
            }
        }
        // Arrival and service plaza remain completely open at player height.
        for(int x=-18;x<=18;x++)for(int z=-16;z<=18;z++)for(int y=97;y<=101;y++){
            if(x*x+z*z<=19*19)level.setBlock(new BlockPos(x,y,z),Blocks.AIR.defaultBlockState(),2);
        }
        // Reinstall the five terminals after opening the plaza; older layouts
        // placed them directly in the volume that had to be cleared.
        set(level,CENTER.offset(12,1,4),ModBlocks.CITADEL_SHOP.get().defaultBlockState());
        set(level,CENTER.offset(-12,1,4),ModBlocks.CITADEL_WORKSHOP.get().defaultBlockState());
        set(level,CENTER.offset(0,1,12),ModBlocks.CITADEL_MISSION_TERMINAL.get().defaultBlockState());
        set(level,CENTER.offset(-8,1,-12),ModBlocks.NEURAL_SCANNER.get().defaultBlockState());
        set(level,CENTER.offset(8,1,-12),ModBlocks.COUNCIL_ARCHIVE.get().defaultBlockState());
        // Final v8 cross-concourse removes the last central bottlenecks.
        carveRoute(level,new BlockPos(-88,96,0),new BlockPos(92,96,0),5);
        carveRoute(level,new BlockPos(0,96,-88),new BlockPos(0,96,75),5);
        // Internal maintenance ladders make every tower level reachable without
        // breaking the solid nine-block separator decks generated by the dome.
        towerLadder(level,0,0,9,44);
        towerLadder(level,-82,12,5,22);
        towerLadder(level,86,8,6,27);
        towerLadder(level,-18,-82,6,30);
        // The cross-concourse above cuts through the contract terminal at z=12.
        // Restore services after ALL carving, not before it.
        set(level,CENTER.offset(12,1,4),ModBlocks.CITADEL_SHOP.get().defaultBlockState());
        set(level,CENTER.offset(-12,1,4),ModBlocks.CITADEL_WORKSHOP.get().defaultBlockState());
        set(level,CENTER.offset(0,1,12),ModBlocks.CITADEL_MISSION_TERMINAL.get().defaultBlockState());
        set(level,CENTER.offset(-8,1,-12),ModBlocks.NEURAL_SCANNER.get().defaultBlockState());
        set(level,CENTER.offset(8,1,-12),ModBlocks.COUNCIL_ARCHIVE.get().defaultBlockState());
        data.setNavigationVersion(6);
    }

    private static void towerLadder(ServerLevel level,int cx,int cz,int radius,int height){
        int x=cx+Math.max(1,radius-2),supportX=x+1,top=96+height-1;
        for(int y=97;y<=top;y++){
            BlockPos support=new BlockPos(supportX,y,cz),ladder=new BlockPos(x,y,cz);
            level.setBlock(support,(y%8==0?Blocks.SEA_LANTERN:ModBlocks.CITADEL_ALLOY.get()).defaultBlockState(),2);
            level.setBlock(ladder,Blocks.LADDER.defaultBlockState().setValue(
                    net.minecraft.world.level.block.LadderBlock.FACING,net.minecraft.core.Direction.WEST),2);
            level.setBlock(ladder.relative(net.minecraft.core.Direction.WEST),Blocks.AIR.defaultBlockState(),2);
        }
        for(int dx=-1;dx<=1;dx++)for(int dz=-1;dz<=1;dz++)for(int y=top;y<=top+2;y++)
            if(!(dx==1&&dz==0))level.setBlock(new BlockPos(x+dx,y,cz+dz),Blocks.AIR.defaultBlockState(),2);
    }

    private static void carveRoute(ServerLevel level,BlockPos from,BlockPos to,int halfWidth){
        int dx=to.getX()-from.getX(),dz=to.getZ()-from.getZ(),steps=Math.max(Math.abs(dx),Math.abs(dz));boolean eastWest=Math.abs(dx)>=Math.abs(dz);
        for(int i=0;i<=steps;i++){double t=i/(double)Math.max(1,steps);int cx=(int)Math.round(from.getX()+dx*t),cz=(int)Math.round(from.getZ()+dz*t);
            for(int w=-halfWidth;w<=halfWidth;w++){int x=cx+(eastWest?0:w),z=cz+(eastWest?w:0);BlockPos floor=new BlockPos(x,96,z);level.setBlock(floor,i%9==0&&w==0?Blocks.SEA_LANTERN.defaultBlockState():ModBlocks.CITADEL_ALLOY.get().defaultBlockState(),2);for(int y=97;y<=101;y++)level.setBlock(new BlockPos(x,y,z),Blocks.AIR.defaultBlockState(),2);}
        }
    }

    public static void ensureRefuge(ServerLevel level) {
        CitadelSavedData data = CitadelSavedData.get(level);
        if (data.getRefugeVersion() >= 3) return;
        // v2 tinha apenas seis pares. Remova somente os sobreviventes do
        // abrigo antes de recriar o elenco, evitando duplicatas em mundos
        // atualizados sem tocar em NPCs que o jogador levou para outro lugar.
        level.getEntitiesOfClass(CitadelNpcEntity.class, new AABB(REFUGE).inflate(28),
                npc -> npc.hasCustomName() && npc.getCustomName().getString().contains("Sobrevivente"))
                .forEach(net.minecraft.world.entity.Entity::discard);
        for (int x = -24; x <= 24; x++) for (int z = -18; z <= 18; z++) {
            set(level, REFUGE.offset(x, -1, z), (x % 5 == 0 && z % 5 == 0)
                    ? Blocks.SEA_LANTERN.defaultBlockState() : ModBlocks.CITADEL_ALLOY.get().defaultBlockState());
            if (Math.abs(x) == 24 || Math.abs(z) == 18)
                set(level, REFUGE.offset(x, 0, z), ModBlocks.CITADEL_GLASS.get().defaultBlockState());
        }
        booth(level, REFUGE.offset(-14, 0, 7), ModBlocks.CITADEL_WORKSHOP.get().defaultBlockState(), ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState());
        booth(level, REFUGE.offset(14, 0, 7), ModBlocks.CITADEL_SHOP.get().defaultBlockState(), ModBlocks.CITADEL_GOLD.get().defaultBlockState());
        booth(level, REFUGE.offset(0, 0, 10), ModBlocks.CITADEL_MISSION_TERMINAL.get().defaultBlockState(), ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState());
        String[] ricks={"Rick D-151","Rick B-921","Rick J-19ζ7","Rick C-500A","Rick K-22","Rick R-426","Rick T-808","Rick Z-144","Rick N-731","Rick Q-009"};
        String[] mortys={"Morty D-151","Morty B-921","Morty J-19ζ7","Morty C-500A","Morty K-22","Morty R-426","Morty T-808","Morty Z-144","Morty N-731","Morty Q-009"};
        for(int i=0;i<10;i++){
            int row=i/5,col=i%5;
            spawnPersonnel(level,CitadelNpcEntity.Variant.RICK,REFUGE.offset(-10+col*5,0,-7+row*3),ricks[i]+" — Sobrevivente");
            spawnPersonnel(level,i%2==0?CitadelNpcEntity.Variant.MORTY_WORKER:CitadelNpcEntity.Variant.MORTY_REBEL,
                    REFUGE.offset(-10+col*5,0,2+row*3),mortys[i]+" — Sobrevivente");
        }
        data.setRefugeVersion(3);
    }

    private static void build(ServerLevel level) {
        BlockState panel = ModBlocks.CITADEL_PANEL.get().defaultBlockState();
        BlockState gold = ModBlocks.CITADEL_GOLD.get().defaultBlockState();
        BlockState circuit = ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState();
        BlockState glass = ModBlocks.CITADEL_GLASS.get().defaultBlockState();
        BlockState alloy = ModBlocks.CITADEL_ALLOY.get().defaultBlockState();

        disk(level, CENTER, 47, panel, alloy);
        dome(level, CENTER.above(), 47, 29, glass, alloy);

        BlockPos east = CENTER.offset(62, 0, 16);
        BlockPos west = CENTER.offset(-62, 0, 16);
        BlockPos south = CENTER.offset(0, 0, 67);
        for (BlockPos district : new BlockPos[]{east, west, south}) {
            disk(level, district, 25, panel, alloy);
            dome(level, district.above(), 25, 18, glass, alloy);
            bridge(level, CENTER, district, 5, panel, circuit);
        }

        // Central transit plaza and portal beacon.
        disk(level, CENTER.above(), 10, Blocks.SMOOTH_QUARTZ.defaultBlockState(), circuit);
        for (int y = 1; y <= 8; y++) set(level, CENTER.above(y), y % 2 == 0 ? circuit : glass);
        ring(level, CENTER.above(10), 7, gold);
        ring(level, CENTER.above(13), 5, circuit);

        // Council tower, commerce, workshop and habitation spires.
        tower(level, CENTER.offset(0, 1, -27), 8, 31, gold, glass);
        tower(level, CENTER.offset(23, 1, -13), 6, 22, alloy, circuit);
        tower(level, CENTER.offset(-23, 1, -13), 6, 25, panel, glass);
        tower(level, east.above(), 8, 24, panel, glass);
        tower(level, west.above(), 8, 24, gold, glass);
        tower(level, south.above(), 9, 28, alloy, circuit);

        // Service counters are deliberately visible from the arrival plaza.
        booth(level, CENTER.offset(15, 1, 9), ModBlocks.CITADEL_SHOP.get().defaultBlockState(), gold);
        booth(level, CENTER.offset(-15, 1, 9), ModBlocks.CITADEL_WORKSHOP.get().defaultBlockState(), circuit);
        booth(level, CENTER.offset(15, 1, -9), ModBlocks.CITADEL_MISSION_TERMINAL.get().defaultBlockState(), circuit);
        booth(level, CENTER.offset(-15, 1, -9), ModBlocks.NEURAL_SCANNER.get().defaultBlockState(), gold);

        // Layered roads make the interior feel like a vertical, inhabited city.
        elevatedRing(level, CENTER, 18, 6, alloy, circuit);
        elevatedRing(level, CENTER, 31, 13, panel, gold);
        spawnCitizens(level);
        spawnC524(level);
    }

