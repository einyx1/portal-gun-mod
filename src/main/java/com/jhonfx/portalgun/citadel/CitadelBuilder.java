    private static void disk(ServerLevel level, BlockPos center, int radius, BlockState floor, BlockState rim) {
        for (int x=-radius;x<=radius;x++) for (int z=-radius;z<=radius;z++) {
            int d2=x*x+z*z;
            if (d2>radius*radius) continue;
            BlockState state=d2>(radius-2)*(radius-2)?rim:((x+z)%11==0?ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState():floor);
            set(level,center.offset(x,0,z),state);
            set(level,center.offset(x,-1,z),Blocks.REINFORCED_DEEPSLATE.defaultBlockState());
        }
    }

    private static void dome(ServerLevel level, BlockPos center, int radius, int height,
                             BlockState glass, BlockState rib) {
        for (int y=0;y<=height;y++) {
            double ringRadius=radius*Math.sqrt(Math.max(0.0,1.0-(y/(double)height)*(y/(double)height)));
            int bound=(int)Math.ceil(ringRadius)+1;
            for(int x=-bound;x<=bound;x++) for(int z=-bound;z<=bound;z++) {
                double d=Math.sqrt(x*x+z*z);
                if(Math.abs(d-ringRadius)>0.62) continue;
                boolean support=(Math.abs(x)<=1||Math.abs(z)<=1||y%8==0);
                set(level,center.offset(x,y,z),support?rib:glass);
            }
        }
    }

    private static void bridge(ServerLevel level, BlockPos from, BlockPos to, int width,
                               BlockState floor, BlockState light) {
        int dx=to.getX()-from.getX(), dz=to.getZ()-from.getZ();
        int steps=Math.max(Math.abs(dx),Math.abs(dz));
        for(int i=0;i<=steps;i++) {
            double t=i/(double)steps;
            int x=(int)Math.round(from.getX()+dx*t), z=(int)Math.round(from.getZ()+dz*t);
            boolean eastWest=Math.abs(dx)>=Math.abs(dz);
            for(int w=-width;w<=width;w++) {
                BlockPos p=new BlockPos(x+(eastWest?0:w),from.getY()+1,z+(eastWest?w:0));
                set(level,p,(i%7==0&&w==0)?light:floor);
            }
        }
    }

    private static void tower(ServerLevel level, BlockPos base, int radius, int height,
                              BlockState wall, BlockState window) {
        for(int y=0;y<=height;y++) {
            int r=Math.max(3,radius-y/10);
            for(int x=-r;x<=r;x++) for(int z=-r;z<=r;z++) {
                double d=Math.sqrt(x*x+z*z);
                if(y==0||y==height) {
                    if(d<=r) set(level,base.offset(x,y,z),wall);
                } else if(d>=r-0.8&&d<=r+0.2) {
                    boolean lit=(y%5==2)&&(Math.abs(x)<=1||Math.abs(z)<=1);
                    set(level,base.offset(x,y,z),lit?window:wall);
                }
            }
        }
    }

    private static void booth(ServerLevel level, BlockPos center, BlockState service, BlockState trim) {
        for(int x=-3;x<=3;x++) for(int z=-2;z<=2;z++) set(level,center.offset(x,0,z),trim);
        for(int x=-3;x<=3;x++) set(level,center.offset(x,4,-2),trim);
        for(int y=1;y<=4;y++) for(int x : new int[]{-3,3}) set(level,center.offset(x,y,-2),trim);
        set(level,center.offset(0,1,-1),service);
        set(level,center.offset(0,2,-2),ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState());
    }

    private static void elevatedRing(ServerLevel level, BlockPos center, int radius, int y,
                                     BlockState floor, BlockState light) {
        for(int i=0;i<360;i+=2) {
            double a=Math.toRadians(i);
            int x=(int)Math.round(Math.cos(a)*radius),z=(int)Math.round(Math.sin(a)*radius);
            for(int w=-2;w<=2;w++) {
                int ix=(int)Math.round(Math.cos(a)*(radius+w)),iz=(int)Math.round(Math.sin(a)*(radius+w));
                set(level,center.offset(ix,y,iz),i%30==0&&w==0?light:floor);
            }
        }
        // Four supports and stairs keep each elevated ring reachable.
        for(net.minecraft.core.Direction d:net.minecraft.core.Direction.Plane.HORIZONTAL) {
            for(int h=0;h<y;h++) set(level,center.relative(d,radius).above(h),ModBlocks.CITADEL_ALLOY.get().defaultBlockState());
        }
    }

    private static void ring(ServerLevel level, BlockPos center, int radius, BlockState state) {
        for(int i=0;i<360;i+=4) {
            double a=Math.toRadians(i);
            set(level,center.offset((int)Math.round(Math.cos(a)*radius),0,(int)Math.round(Math.sin(a)*radius)),state);
        }
    }

