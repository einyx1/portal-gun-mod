    /**
     * The Curve is made from persistent entities instead of a particle cloud.
     * That keeps its shape visible from every angle and avoids respawning
     * hundreds of particles every tick.
     */
    private static void decorateCurveWing(ServerLevel level) {
        BlockPos wing=CENTER.offset(0,0,-76);
        boolean exists=!level.getEntitiesOfClass(com.jhonfx.portalgun.entity.CurveNodeEntity.class,
                new AABB(wing).inflate(18), n -> true).isEmpty();
        if(!exists) {
            // Build ring-by-ring, keeping a reference to the previous node in each
            // ring so we can link() them into a connected lattice (tether particles).
            com.jhonfx.portalgun.entity.CurveNodeEntity firstInRing = null;
            com.jhonfx.portalgun.entity.CurveNodeEntity previous = null;
            for(int ring=0;ring<4;ring++) {
                int nodes=10+ring*4;
                double radius=2.4+ring*1.45;
                firstInRing = null;
                previous = null;
                for(int i=0;i<nodes;i++) {
                    double angle=i*Math.PI*2.0/nodes+ring*.53;
                    double y=4.1+(ring-1.5)*1.15+Math.sin(angle*3.0)*.72;
                    com.jhonfx.portalgun.entity.CurveNodeEntity node =
                            com.jhonfx.portalgun.init.ModEntityTypes.CURVE_NODE.get().create(level);
                    if(node==null)continue;
                    node.setRing(ring);
                    node.setBase(wing.getX()+.5+Math.cos(angle)*radius, wing.getY()+y,
                            wing.getZ()+.5+Math.sin(angle)*radius);
                    node.setYRot((float)Math.toDegrees(-angle));
                    level.addFreshEntity(node);

                    if (firstInRing == null) firstInRing = node;
                    if (previous != null) previous.linkTo(node);
                    previous = node;
                }
                // Close the ring loop
                if (previous != null && firstInRing != null) previous.linkTo(firstInRing);
            }
        }
        createGuide(level,wing.offset(0,3,16),"CURVA FINITA CENTRAL  ↓");
        createGuide(level,CENTER.offset(0,4,-38),"CURVA FINITA CENTRAL  →");
    }

    private static void createGuide(ServerLevel level,BlockPos pos,String label) {
        boolean exists=!level.getEntitiesOfClass(ArmorStand.class,new AABB(pos).inflate(2),
                stand -> stand.getPersistentData().getBoolean("PortalGunCurveGuide")).isEmpty();
        if(exists)return;
        ArmorStand guide=EntityType.ARMOR_STAND.create(level); if(guide==null)return;
        guide.moveTo(pos.getX()+.5,pos.getY(),pos.getZ()+.5,0,0);
        guide.setInvisible(true); guide.setInvulnerable(true); guide.setNoGravity(true); configureStand(guide,false);
        guide.setCustomName(net.minecraft.network.chat.Component.literal(label)); guide.setCustomNameVisible(true);
        guide.getPersistentData().putBoolean("PortalGunCurveGuide",true);
        level.addFreshEntity(guide);
    }

    private static void configureStand(ArmorStand stand,boolean small) {
        net.minecraft.nbt.CompoundTag tag=new net.minecraft.nbt.CompoundTag();
        stand.saveWithoutId(tag);tag.putBoolean("Marker",true);tag.putBoolean("Small",small);
        tag.putBoolean("Invisible",true);tag.putBoolean("Invulnerable",true);tag.putBoolean("NoGravity",true);
        stand.load(tag);
    }

    /**
     * 0.9 combat layout. It deliberately replaces only public streets and empty
     * air above them, preserving player interiors while fixing the old vertical
     * rings that had no climbable route.
     */
    private static void rebuildCombatCitadel(ServerLevel level) {
        BlockState panel=ModBlocks.CITADEL_PANEL.get().defaultBlockState();
        BlockState alloy=ModBlocks.CITADEL_ALLOY.get().defaultBlockState();
        BlockState gold=ModBlocks.CITADEL_GOLD.get().defaultBlockState();
        BlockState circuit=ModBlocks.CITADEL_CIRCUIT.get().defaultBlockState();
        BlockState glass=ModBlocks.CITADEL_GLASS.get().defaultBlockState();

        // A broad, readable ground plan: arrival plaza, four districts and an
        // unobstructed central avenue. Embedded light prevents hostile spawns.
        publicPlaza(level,CENTER.above(),34,panel,alloy,circuit);
        avenue(level,CENTER.offset(0,1,-76),CENTER.offset(0,1,69),7,panel,circuit);
        avenue(level,CENTER.offset(-64,1,16),CENTER.offset(64,1,16),6,alloy,circuit);
        publicPlaza(level,CENTER.offset(62,1,16),19,panel,gold,circuit);
        publicPlaza(level,CENTER.offset(-62,1,16),19,alloy,gold,circuit);
        publicPlaza(level,CENTER.offset(0,1,67),20,panel,alloy,circuit);
        publicPlaza(level,CENTER.offset(0,1,-76),17,alloy,gold,circuit);

        // Two spacious skyline decks. Each has four real ramps: one block of
        // height per three blocks of travel, so every floor is walkable.
        skyDeck(level,CENTER,24,8,alloy,gold,circuit);
        skyDeck(level,CENTER,38,15,panel,alloy,circuit);
        for(net.minecraft.core.Direction d:net.minecraft.core.Direction.Plane.HORIZONTAL) {
            accessibleRamp(level,CENTER,d,24,8,5,panel,circuit);
            accessibleRamp(level,CENTER,d,38,15,5,alloy,circuit);
        }

        // Council chamber and combat-training platform give the city a clear
        // silhouette without sealing the paths under decorative geometry.
        openCouncil(level,CENTER.offset(0,1,-31),gold,glass,circuit);
        trainingArena(level,CENTER.offset(0,1,35),alloy,gold,circuit);
        lightPublicSpace(level,CENTER,82);
    }

    private static void publicPlaza(ServerLevel level,BlockPos center,int radius,BlockState floor,BlockState rim,BlockState light){
        for(int x=-radius;x<=radius;x++)for(int z=-radius;z<=radius;z++){
            int d=x*x+z*z;if(d>radius*radius)continue;
            BlockPos p=center.offset(x,0,z);
            set(level,p,d>(radius-2)*(radius-2)?rim:((x*x+z*z)%37==0?light:floor));
            if((x+z)%9==0)set(level,p.below(),Blocks.SEA_LANTERN.defaultBlockState());
            for(int y=1;y<=3;y++)if(level.getBlockState(p.above(y)).isAir())set(level,p.above(y),Blocks.AIR.defaultBlockState());
        }
    }

    private static void avenue(ServerLevel level,BlockPos from,BlockPos to,int width,BlockState floor,BlockState light){
        int dx=to.getX()-from.getX(),dz=to.getZ()-from.getZ(),steps=Math.max(Math.abs(dx),Math.abs(dz));
        for(int i=0;i<=steps;i++){
            double t=i/(double)steps;int x=(int)Math.round(from.getX()+dx*t),z=(int)Math.round(from.getZ()+dz*t);
            boolean eastWest=Math.abs(dx)>=Math.abs(dz);
            for(int w=-width;w<=width;w++){
                BlockPos p=new BlockPos(x+(eastWest?0:w),from.getY(),z+(eastWest?w:0));
                set(level,p,(i%8==0&&Math.abs(w)==width-1)?light:floor);
                for(int y=1;y<=4;y++)set(level,p.above(y),Blocks.AIR.defaultBlockState());
            }
        }
    }

    private static void skyDeck(ServerLevel level,BlockPos center,int radius,int height,BlockState floor,BlockState rim,BlockState light){
        for(int i=0;i<360;i+=2){
            double a=Math.toRadians(i);
            for(int w=-3;w<=3;w++){
                int x=(int)Math.round(Math.cos(a)*(radius+w));int z=(int)Math.round(Math.sin(a)*(radius+w));
                BlockPos p=center.offset(x,height,z);set(level,p,Math.abs(w)==3?rim:(i%24==0?light:floor));
                set(level,p.below(),i%12==0?Blocks.SEA_LANTERN.defaultBlockState():floor);
                for(int y=1;y<=3;y++)set(level,p.above(y),Blocks.AIR.defaultBlockState());
            }
        }
    }

    private static void accessibleRamp(ServerLevel level,BlockPos center,net.minecraft.core.Direction direction,int radius,int height,int width,BlockState floor,BlockState light){
        int length=height*3;
        for(int step=0;step<=length;step++){
            int y=Math.min(height,step/3);int distance=radius-length+step;
            BlockPos middle=center.relative(direction,distance).above(y);
            net.minecraft.core.Direction side=direction.getClockWise();
            for(int w=-width;w<=width;w++){
                BlockPos p=middle.relative(side,w);set(level,p,(step%9==0&&Math.abs(w)==width)?light:floor);
                for(int clear=1;clear<=3;clear++)set(level,p.above(clear),Blocks.AIR.defaultBlockState());
            }
        }
    }

